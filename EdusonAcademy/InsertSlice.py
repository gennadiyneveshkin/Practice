# Вставить число num в список ref_list начиная с позиции start, повторяя его rep раз.
def list_insert (ref_list, start, num, rep):
    list_insert[start:start] = [num]*rep

# ref_list[start:start] = [num] * rep
# «на место пустого среза, начинающегося в позиции start, вставь этот список».
# [num] - список из одного элемента, [num] * rep → список из rep копий num,
# это и есть блок, который мы хотим вставить

# ref_list[start:start] — «пустой срез» как точка вставки
# это пустой срез, без элементов который «живёт» ровно между элементами:
# перед элементом с индексом start (если он есть),
# или в самом конце, если start == len(ref_list)
# такой пустой срез не возвращает данные, он обозначает позицию в списке.
# ref_list[start:start] = [num] * rep
# означает буквально: «на место пустого среза, начинающегося в позиции start, вставь этот список».
# При этом элементы, которые были начиная с start, сдвигаются вправо;
# длина списка увеличивается ровно на rep.