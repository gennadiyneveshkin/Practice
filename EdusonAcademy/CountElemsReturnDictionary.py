# Напишите функцию count_elements, которая принимает на вход коллекцию
# (список, кортеж, множество или строку) и возвращает словарь.
# В нем ключами должны быть уникальные элементы коллекции,
# а значениями - количество их вхождений в данную коллекцию.
# В результате верните получивышийся словарь.

def count_elements(data):
    res = {}

    # Идем по элементам коллекции
    for el in data:

        # Если элемент коллекции уже является ключом результирующего словаря
        # увеличиваем его значение на 1
        if el in res:
            res[el] += 1

        # Если нет - добавляем этот элемент в качестве ключа, а значение ставим равным 1
        else:
            res[el] = 1
    return res


