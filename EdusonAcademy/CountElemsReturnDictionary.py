def count_elements(data):
    counts = {}
    for el in data:

        # counts.get(el, 0) пытается получить значение по ключу el из словаря counts.
        # Если ключ el уже есть, вернётся его текущее значение (например, 3).
        # Если ключа нет, вернётся значение по умолчанию, то есть 0. Так мы избегаем ошибки KeyError.
        # + 1 к полученному значению прибавляем единицу.
        # Если элемент уже встречался, его счётчик вырастет на 1.
        # Если не встречался, мы фактически ставим счётчик в 1 (потому что было 0, плюс 1).

        counts[el] = counts.get(el, 0) + 1
    return counts