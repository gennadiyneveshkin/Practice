# Напишите функцию sort_dict, которая принимает на вход словарь d,
# тип сортировки type (keywise или valuewise)
# и порядок сортировки order (asc или desc).
# Функция должна возвращать отсортированный словарь по ключам или значениям,
# в зависимости от переданных параметров.

def sort_dict(d, type, order):
    if type == "keywise":
        idx = 0
    else:
        idx = 1

    if order == "desc":
        reverse_check = True
    else:
        reverse_check = False

    return dict(sorted(d.items(), key=lambda x: x[idx], reverse=reverse_check))

# Что происходит по шагам
# d.items() — даёт итератор по парам (ключ, значение). В памяти это выглядит как последовательность кортежей, например: [('a', 1), ('b', 3), ('c', 2)].
# sorted(..., key=lambda x: x[idx], ...) — сортирует эту последовательность:
# key=lambda x: x[idx] означает: «для каждого кортежа x бери элемент с индексом idx и по нему сортируй».
# Если idx == 0 (случай keywise), сортируем по ключам: x[0].
# Если idx == 1 (случай valuewise), сортируем по значениям: x[1].
# reverse=reverse_check задаёт направление:
# True → сортировка по убыванию.
# False → по возрастанию.
# Результат sorted() — новый список кортежей, уже отсортированный.
# dict(...) — превращает отсортированный список кортежей обратно в словарь. В Python 3.7+ порядок элементов в словаре сохраняется, поэтому итоговый словарь будет «отсортированным» в нужном порядке.
# return — функция отдаёт этот новый словарь как результат.



